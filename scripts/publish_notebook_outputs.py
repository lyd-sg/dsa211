"""Extract images from the executed notebook into GitHub-renderable figures.

Usage: python scripts/publish_notebook_outputs.py results/online_shoppers_revised_executed.ipynb
This does not change model code, decisions or results.
"""
from __future__ import annotations

import base64
import re
import shutil
import sys
from pathlib import Path

import nbformat


def slugify(value: str) -> str:
    value = re.sub(r"[^a-z0-9]+", "-", value.lower()).strip("-")
    return value[:58].rstrip("-") or "notebook-figure"


def main() -> None:
    if len(sys.argv) != 2:
        raise SystemExit("Pass the path to an executed .ipynb notebook")
    notebook_path = Path(sys.argv[1])
    if not notebook_path.exists():
        raise SystemExit(f"Notebook not found: {notebook_path}")
    book = nbformat.read(notebook_path, as_version=4)
    figures_dir = notebook_path.parent / "figures"
    if figures_dir.exists():
        shutil.rmtree(figures_dir)
    figures_dir.mkdir(parents=True)

    entries: list[tuple[str, str]] = []
    section = "Notebook figure"
    count = 0
    for cell in book.cells:
        if cell.cell_type == "markdown":
            for line in cell.source.splitlines():
                if line.startswith("## "):
                    section = line.removeprefix("## ").strip()
        elif cell.cell_type == "code":
            for output in cell.get("outputs", []):
                encoded = output.get("data", {}).get("image/png")
                if not encoded:
                    continue
                count += 1
                name = f"{count:02d}-{slugify(section)}.png"
                image_bytes = base64.b64decode("".join(encoded) if isinstance(encoded, list) else encoded)
                (figures_dir / name).write_bytes(image_bytes)
                entries.append((section, name))

    if not entries:
        raise SystemExit("No plots found in executed notebook; refusing to publish empty results")

    readme = [
        "# DSA211 — Executed PRD v2.0 notebook",
        "",
        "These are the **actual figures** generated by GitHub Actions from the latest PRD v2.0 "
        "notebook on this branch. The original analysis code and dataset have not been changed.",
        "",
        "**[View the fully executed notebook, including tables and plots]"
        "(online_shoppers_revised_executed.ipynb)**",
        "",
        "Results reflect the notebook's training-only cross-validation protocol. "
        "Figures do not establish independently validated test performance or voucher effects.",
        "",
        "## Figures",
        "",
    ]
    for title, filename in entries:
        readme.extend([f"### {title}", "", f"![{title}](figures/{filename})", ""])
    (notebook_path.parent / "README.md").write_text("\n".join(readme), encoding="utf-8")
    print(f"Published {len(entries)} figure(s) from {notebook_path}")
    for title, filename in entries:
        print(f"  {title}: {filename}")


if __name__ == "__main__":
    main()
